def fmt(x):
    if x is None:return '—'
    if isinstance(x,(int,np.integer)):return str(x)
    if isinstance(x,(float,np.floating)):return f'{x:.6g}'
    return str(x).replace('|','\\|')

def table(headers,rows):
    return '\n| '+' | '.join(map(fmt,headers))+' |\n| '+' | '.join(['---']*len(headers))+' |\n'+''.join('| '+' | '.join(map(fmt,row))+' |\n' for row in rows)+'\n'

